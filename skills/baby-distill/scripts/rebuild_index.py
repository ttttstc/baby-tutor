def parse_fm(text):
    m = re.match(r'^---\n(.*?)\n---', text, re.S)
    if not m: return {}
    fm_raw = m.group(1)
    fm = {}
    for k in ['id','title','category','evidence','problem']:
        mm = re.search(rf'^{k}:\s*(.*)$', fm_raw, re.M)
        fm[k] = mm.group(1).strip() if mm else ''
    am = re.search(r'^age_range:\s*\[(.*?)\]', fm_raw, re.S | re.M)
    fm['_ages'] = [a.strip() for a in am.group(1).split(',')] if am else []
    ai = re.search(r'^also_in:\s*\[(.*?)\]', fm_raw, re.S | re.M)
    fm['_also'] = [a.strip() for a in ai.group(1).split(',')] if ai else []
    return fm

def main():
    cats = collections.defaultdict(list)
    for p in sorted(glob.glob(os.path.join(REFS, '**', '*.md'), recursive=True)):
        if '_index' in p or os.sep + '_' in p: continue
        d = os.path.dirname(p); cat = os.path.basename(d)
        if not re.match(r'^\d\d-', cat): continue
        fm = parse_fm(open(p, encoding='utf-8').read())
        if not fm.get('id'): continue
        cats[cat].append(fm)

    total = 0
    for cat, rows in sorted(cats.items()):
        disp = cat.split('-', 1)[1]
        rules = CLUSTERS.get(cat) or [('全部', '该分类全部条目', r'.')]
        buckets = collections.OrderedDict((n, []) for n, _, _ in rules)
        desc = {n: d for n, d, _ in rules}
        for fm in rows:
            hay = fm['title'] + ' ' + fm['problem']
            for n, _, rx in rules:
                if re.search(rx, hay): buckets[n].append(fm); break
            else:
                buckets.setdefault(FALLBACK[0], []).append(fm)
                desc.setdefault(FALLBACK[0], FALLBACK[1])

        catdir = os.path.join(IDX, 'clusters', cat)
        os.makedirs(catdir, exist_ok=True)
        # 清掉本分类旧子索引，避免改名后残留
        for old in glob.glob(os.path.join(catdir, '*.md')): os.remove(old)

        lvl1 = []; n = 0
        for name, arr in buckets.items():
            if not arr: continue
            n += 1; total += len(arr)
            fn = f'{n:02d}-' + re.sub(r'[/\\:：]', '·', name) + '.md'
            sub = [f'# {cat} · {name}（{len(arr)} 条）', '',
                   f'> 路径前缀 `references/{cat}/`',
                   '> **匹配**：先比「用户会怎么问」（逐字重合=强命中），再比「判断」。「月龄」列不符的先降级。',
                   '> **红旗**：回复前先扫条目 `red_flags`，命中先走「先说安全」。', '',
                   '| id | tier | 月龄 | 判断 | 用户会怎么问 |', '|---|---|---|---|---|']
            for fm in arr:
                sub.append(f"| `{fm['id']}` | {fm['evidence']} | {fmt_ages(fm['_ages'])} | {fm['title'][:30]} | {fm['problem'][:44]} |")
            open(os.path.join(catdir, fn), 'w', encoding='utf-8', newline='\n').write('\n'.join(sub) + '\n')
            lvl1.append((name, len(arr), desc.get(name, ''), f'_index/clusters/{cat}/{fn}'))

        # 跨类挂靠
        subrows = []
        for oc, orows in cats.items():
            if oc == cat: continue
            od = oc.split('-', 1)[1]
            for fm in orows:
                if od in fm['_also']:
                    subrows.append(f"| `{fm['id']}` | {fm['evidence']} | {fmt_ages(fm['_ages'])} | {fm['title'][:30]} | （主分类 {oc}） |")
        if subrows:
            open(os.path.join(catdir, '_副.md'), 'w', encoding='utf-8', newline='\n').write(
                '\n'.join([f'# {cat} · 跨类挂靠（{len(subrows)} 条，正文在别类）', '',
                           f'> 这些条目的 `also_in` 含「{disp}」；全文去其**主分类目录** Read。', '',
                           '| id | tier | 月龄 | 判断 | 主分类 |', '|---|---|---|---|---|'] + subrows) + '\n')

        # 一级索引
        L = [f'# 索引 · {cat}（{len(rows)} 条 / {len(lvl1)} 簇）', '',
             f'> 路径前缀 `references/{cat}/`',
             '> **两级检索**：先在本页按用户问题选**簇** → 再 Read 该簇子索引做双通道匹配（「用户会怎么问」逐字命中 > 「判断」同理）。',
             '> **红旗**：本类所有条目回复前先扫 `red_flags`，命中先走「先说安全」。', '',
             '| 簇 | 条数 | 一句话 | 子索引 |', '|---|---|---|---|']
        for name, cnt, d, path in lvl1:
            L.append(f'| {name} | {cnt} | {d} | `{path}` |')
        if subrows:
            L.append(f'\n> 另有跨类挂靠 {len(subrows)} 条（正文在别类）：见 `_index/clusters/{cat}/_副.md`')
        open(os.path.join(IDX, cat + '.md'), 'w', encoding='utf-8', newline='\n').write('\n'.join(L) + '\n')

    print(f'重建完成: {total} 条条目, {len(cats)} 个分类一级索引 + 二级簇索引')

